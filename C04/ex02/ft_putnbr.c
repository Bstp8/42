#include <unistd.h>

void ft_putnbr(int nb)
{
	if (nb >= 10)
		ft_putnbr(nb / 10);
	char c = (nb % 10) + '0';
	write(1, &c, 1);
}

int main()
{
	long nb;
	
	nb = 465659844956;
	ft_putnbr(nb);
	return 0;
}
